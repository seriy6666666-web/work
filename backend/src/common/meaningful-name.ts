import { Transform } from 'class-transformer';
import { applyDecorators } from '@nestjs/common';
import { IsString, Matches, MaxLength, MinLength } from 'class-validator';

/**
 * Проверка названий, которые вводит человек: участков, навыков, операций, изделий.
 *
 * Чего эта проверка НЕ делает: она не отличает осмысленное слово от бессмысленного.
 * Соблазн ловить «asdfgh» по отсутствию гласных или по клавиатурным сочетаниям
 * велик, но на этом производстве он ломается сразу: «ЧПУ Сварка», «Пайка ХТ»,
 * «АКБ-48В» — настоящие названия, и любая такая эвристика отвергала бы их. Ложный
 * отказ хуже мусорной записи: мусор видно и можно исправить, а невозможность
 * завести нужную операцию останавливает работу.
 *
 * Поэтому проверяем то, что проверяется надёжно: длину, наличие букв и отсутствие
 * явного «мусора вроде ааааа». А от расхождений «Сортировка ячеек» / «сортировка
 * ячейки» защищает не эта проверка, а справочник: название вводится один раз и
 * дальше выбирается из списка.
 */

/** Схлопываем внутренние пробелы и обрезаем края: «Пайка   шин » → «Пайка шин». */
export const NormalizeName = () =>
  Transform(({ value }) => (typeof value === 'string' ? value.trim().replace(/\s+/g, ' ') : value));

/** Хотя бы одна буква: «1024», «---» и «???» названием не считаются. */
const HAS_LETTER = /[\p{L}]/u;

/**
 * Один и тот же символ четыре раза подряд. Четыре, а не три: «Класс III» и
 * подобные римские цифры в названиях встречаются, а «ааааа» — уже мусор.
 */
const NO_LONG_REPEAT = /^(?!.*(.)\1{3,}).*$/su;

export function MeaningfulName(max = 120) {
  return applyDecorators(
    NormalizeName(),
    IsString(),
    MinLength(2, { message: 'Название слишком короткое — минимум 2 символа' }),
    MaxLength(max, { message: `Название слишком длинное — максимум ${max} символов` }),
    Matches(HAS_LETTER, { message: 'В названии должна быть хотя бы одна буква' }),
    Matches(NO_LONG_REPEAT, {
      message: 'В названии один и тот же символ повторяется подряд слишком много раз',
    }),
  );
}
