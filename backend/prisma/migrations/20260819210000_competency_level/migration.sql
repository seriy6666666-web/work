-- Ступени допуска вместо «умеет / не умеет».
--
-- Двоичное «умеет» не совпадало с тем, как на участке распределяют работу:
-- между «никогда не делал» и «может учить других» лежат две ступени, и
-- начальнику важно их различать. Ученика ставить можно, но рядом с наставником,
-- а не одного на смену.
--
-- Отсутствие записи означает «нет допуска» — отдельного значения не заводим.
CREATE TYPE "CompetencyLevel" AS ENUM ('LEARNING', 'ALLOWED', 'MENTOR');

-- Все прежние отметки означали самостоятельную работу.
ALTER TABLE "Competency" ADD COLUMN "level" "CompetencyLevel" NOT NULL DEFAULT 'ALLOWED';
