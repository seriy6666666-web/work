-- Сколько штук операции приходится на одно изделие.
--
-- «Резка силового провода» даёт два провода на батарею, а система считала 1:1:
-- заказали 100 батарей — в операции стояло 100 вместо 200. И посчитать готовую
-- продукцию было невозможно в принципе: 200 нарезанных проводов — это 100
-- батарей, а не 200.
--
-- По умолчанию 1 — у всех существующих шагов поведение не меняется.
ALTER TABLE "ProductOperation" ADD COLUMN "perUnit" INTEGER NOT NULL DEFAULT 1;

-- То же у операции заказа: коэффициент переносится из техкарты при создании
-- заказа и остаётся в операции, чтобы пересчёт готовой продукции не зависел от
-- того, правил ли кто-то техкарту после запуска заказа.
ALTER TABLE "Operation" ADD COLUMN "perUnit" INTEGER NOT NULL DEFAULT 1;
