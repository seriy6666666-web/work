-- Архивный статус заказа.
--
-- Заказ, по которому уже отчитались, удалять нельзя: выработка и брак — история
-- производства, и её пропажа задним числом молча меняет статистику за период.
-- Такой заказ уходит в архив: из работы пропадает, в отчётах остаётся. Так же
-- сделано с уволенными сотрудниками и с операциями справочника.
ALTER TYPE "OrderStatus" ADD VALUE IF NOT EXISTS 'ARCHIVED';
